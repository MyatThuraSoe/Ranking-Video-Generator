"""Create the Ed25519 signing key pair used for LRBar-RankGen licenses.

Run once from the repository root:

    python licensing/keygen.py

This writes:

* ``licensing/private_key.pem``  – SECRET signing key. Never ship or commit it.
* ``ranking_video_studio/utils/license_public_key.py`` – public key compiled
  into the app (safe to ship).

Back the private key up somewhere safe (password manager / encrypted drive).
If it is lost you cannot issue keys for the existing app build; if it leaks,
anyone can issue their own keys. Use ``--force`` to deliberately rotate the
pair (all previously issued keys stop working).
"""
import argparse
import base64
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP_UTILS = os.path.join(os.path.dirname(HERE), "ranking_video_studio", "utils")
PRIVATE_PATH = os.path.join(HERE, "private_key.pem")
PUBLIC_MODULE = os.path.join(APP_UTILS, "license_public_key.py")

PUBLIC_MODULE_TEMPLATE = '''"""Ed25519 public key for offline LRBar-RankGen license verification.

GENERATED by ``licensing/keygen.py``. Do not edit by hand.

The matching private key is kept offline by the vendor; only this public key
is compiled into the application. Re-running keygen.py with ``--force``
replaces this key and invalidates every previously issued license.
"""

KEY_ID = "{key_id}"
PUBLIC_KEY_B64 = "{public_key}"
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true",
                        help="overwrite an existing private key")
    args = parser.parse_args(argv)

    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey,
    )

    if os.path.exists(PRIVATE_PATH) and not args.force:
        raise SystemExit(
            f"{PRIVATE_PATH} already exists.\n"
            "Keep it and run issue_license.py, or pass --force to rotate "
            "the key pair (invalidates all existing licenses).")

    private = Ed25519PrivateKey.generate()
    pem = private.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    public_raw = private.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )
    public_b64 = base64.b64encode(public_raw).decode("ascii")
    key_id = hashlib.sha256(public_raw).hexdigest()[:12]

    os.makedirs(os.path.dirname(PRIVATE_PATH), exist_ok=True)
    with open(PRIVATE_PATH, "wb") as fh:
        fh.write(pem)
    try:  # best-effort read-only for the current user on POSIX
        os.chmod(PRIVATE_PATH, 0o600)
    except OSError:
        pass

    os.makedirs(APP_UTILS, exist_ok=True)
    with open(PUBLIC_MODULE, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(PUBLIC_MODULE_TEMPLATE.format(
            key_id=key_id, public_key=public_b64))

    print(f"Private key : {PRIVATE_PATH}")
    print(f"Public key  : {PUBLIC_MODULE}")
    print(f"Key ID      : {key_id}")
    print("\nBack up private_key.pem and keep it secret. "
          "The app can now verify keys issued by issue_license.py.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
